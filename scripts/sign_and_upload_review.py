#!/usr/bin/env python3
import argparse
import hmac
import hashlib
import json
import subprocess
import sys
import os

REPORT_HEADER = "### Secured Agentic Review Report"

def get_git_head_sha():
    try:
        head_sha = subprocess.check_output(["git", "rev-parse", "HEAD"]).decode("utf-8").strip()
        return head_sha
    except subprocess.CalledProcessError as e:
        print(f"Error: git execution failed: {e}")
        sys.exit(1)

def get_active_pr_number():
    # Automatically query GitHub CLI for the PR associated with the current branch
    try:
        result = subprocess.check_output(
            ["gh", "pr", "view", "--json", "number"],
            stderr=subprocess.DEVNULL
        ).decode("utf-8")
        pr_data = json.loads(result)
        return str(pr_data["number"])
    except Exception:
        # Fallback to environment variable if set
        return os.getenv("PR_NUMBER")

def load_review_report():
    report_file = "agent-review-report.json"
    if not os.path.exists(report_file):
        print(f"Error: {report_file} not found. Ensure Claude generated the report file.")
        sys.exit(1)

    with open(report_file, "r", encoding="utf-8") as f:
        try:
            return json.load(f)
        except json.JSONDecodeError as e:
            print(f"Error parsing {report_file} as JSON: {e}")
            sys.exit(1)

def main():
    parser = argparse.ArgumentParser(description="Sign and upload agentic review report to GitHub PR.")
    parser.add_argument(
        "--pr-number",
        type=str,
        help="The GitHub PR number to comment on (auto-detected via gh CLI if omitted)."
    )
    args = parser.parse_args()

    # 1. Signing secret comes only from the environment, never the command line
    #    (arguments end up in shell history, process lists and agent transcripts).
    signing_secret = os.getenv("AGENT_SIGNING_SECRET")
    if not signing_secret:
        print("Error: AGENT_SIGNING_SECRET environment variable is missing.")
        sys.exit(1)

    # 2. Load the structured evaluation file generated by Claude Code
    payload = load_review_report()
    if not isinstance(payload.get("passed"), bool):
        print('Error: "passed" in the report must be a JSON boolean (true or false), not a string.')
        sys.exit(1)
    for key in ("accepted_findings", "fixed_findings", "rejected_findings"):
        if not isinstance(payload.get(key, []), list):
            print(f'Error: "{key}" in the report must be a list.')
            sys.exit(1)
    # Accepted findings block the gate, so the review passes only when there are none
    accepted_count = len(payload.get("accepted_findings", []))
    if payload["passed"] != (accepted_count == 0):
        print(f'Error: "passed" is {str(payload["passed"]).lower()} but the report has {accepted_count} accepted finding(s). '
              'The review passes only when there are no accepted findings.')
        sys.exit(1)

    # 3. Securely enforce commit SHA binding
    head_sha = get_git_head_sha()
    payload["commit_sha"] = head_sha

    # 4. Resolve PR Number (CLI flag -> GitHub CLI auto-detect -> Environment Variable)
    pr_number = args.pr_number or get_active_pr_number()
    if not pr_number:
        print("Error: Could not determine active PR number. Provide via --pr-number or ensure you are on a branch with an open PR.")
        sys.exit(1)

    print(f"Processing signed review report for PR #{pr_number} (Commit: {head_sha[:7]})...")

    # 5. Serialise once; the gate verifies the HMAC over exactly this text from the comment
    payload_json_str = json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False)

    # 6. Compute HMAC SHA-256 Signature
    signature = hmac.new(
        signing_secret.encode("utf-8"),
        payload_json_str.encode("utf-8"),
        hashlib.sha256
    ).hexdigest()

    # 7. Format PR comment body with embedded cryptographic proof block
    comment_body = f"{REPORT_HEADER}\n\n"
    comment_body += f"**Commit:** `{head_sha}`\n"
    comment_body += f"**Status:** {'PASSED' if payload['passed'] else 'FAILED'}\n"
    comment_body += f"**Summary:** {payload.get('summary', 'No summary provided.')}\n\n"
    comment_body += f"```json\n{payload_json_str}\n```\n"
    comment_body += f"<!-- AGENT_SIGNATURE: sha256={signature} -->"

    print(f"Uploading signed report to PR #{pr_number} via GitHub CLI...")

    try:
        # Body goes through stdin: avoids command-line length limits on long reports
        subprocess.run(
            ["gh", "pr", "comment", pr_number, "--body-file", "-"],
            input=comment_body.encode("utf-8"),
            check=True
        )
        print("Signed agent review successfully posted to GitHub PR.")
    except (subprocess.CalledProcessError, FileNotFoundError) as e:
        print(f"Error: failed to post PR comment via GitHub CLI: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
