#!/usr/bin/env python3
import hmac
import hashlib
import json
import subprocess
import sys
import os

SIGNING_SECRET = os.getenv("AGENT_SIGNING_SECRET")

def get_git_head_sha():
    try:
        head_sha = subprocess.check_output(["git", "rev-parse", "HEAD"]).decode("utf-8").strip()
        return head_sha
    except subprocess.CalledProcessError as e:
        print(f"❌ Git execution error: {e}")
        sys.exit(1)

def get_active_pr_number(head_sha):
    # Automatically query GitHub CLI for the PR associated with the current branch/SHA
    try:
        result = subprocess.check_output(
            ["gh", "pr", "view", "--json", "number,headRefOid"],
            stderr=subprocess.DEVNULL
        ).decode("utf-8")
        pr_data = json.loads(result)
        return str(pr_data["number"])
    except Exception:
        # Fallback to environment variable if set
        return os.getenv("PR_NUMBER")

def load_review_report():
    report_file = "agent-review-report.json"
    if not os.path.exists(report_file):
        print(f"❌ Error: {report_file} not found. Ensure Claude generated the report file.")
        sys.exit(1)
        
    with open(report_file, "r") as f:
        try:
            return json.load(f)
        except json.JSONDecodeError as e:
            print(f"❌ Error parsing {report_file} as JSON: {e}")
            sys.exit(1)

def main():
    if not SIGNING_SECRET:
        print("❌ Error: AGENT_SIGNING_SECRET environment variable is missing.")
        print("Run: export AGENT_SIGNING_SECRET='your-secret-key'")
        sys.exit(1)

    # 1. Load the structured evaluation file generated by Claude Code
    payload = load_review_report()
    
    # 2. Securely enforce commit SHA binding
    head_sha = get_git_head_sha()
    payload["commit_sha"] = head_sha

    pr_number = get_active_pr_number(head_sha)
    if not pr_number:
        print("❌ Error: Could not determine active PR number. Ensure you are on a branch with an open PR or set PR_NUMBER=<id>.")
        sys.exit(1)

    print(f"🤖 Processing signed review report for PR #{pr_number} (Commit: {head_sha[:7]})...")

    # 3. Canonical JSON sorting for deterministic signing
    canonical_json_str = json.dumps(payload, sort_keys=True)

    # 4. Compute HMAC SHA-256 Signature
    signature = hmac.new(
        SIGNING_SECRET.encode('utf-8'), 
        canonical_json_str.encode('utf-8'), 
        hashlib.sha256
    ).hexdigest()

    # 5. Format PR comment body with embedded cryptographic proof block
    comment_body = f"### 🤖 Secured Agentic Review Report\n\n"
    comment_body += f"**Commit:** `{head_sha}`\n"
    comment_body += f"**Status:** {'✅ PASSED' if payload.get('passed', False) else '❌ FAILED'}\n"
    comment_body += f"**Summary:** {payload.get('summary', 'No summary provided.')}\n\n"
    comment_body += f"```json\n{json.dumps(payload, indent=2)}\n```\n"
    comment_body += f"<!-- AGENT_SIGNATURE: sha256={signature} -->"

    print(f"🚀 Uploading signed report to PR #{pr_number} via GitHub CLI...")
    
    try:
        subprocess.run(
            ["gh", "pr", "comment", pr_number, "--body", comment_body],
            check=True
        )
        print("✅ Signed agent review successfully posted to GitHub PR.")
    except subprocess.CalledProcessError as e:
        print(f"❌ Failed to post PR comment via GitHub CLI: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
